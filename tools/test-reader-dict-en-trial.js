const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { build, parseMatch } = require('./build-reader-dict-en-trial');
const base = path.resolve(__dirname, '../prototype-0.5-media-shell/data');
const source = JSON.parse(fs.readFileSync(path.join(base, 'research/reader-dict-it-en-sample.json'), 'utf8'));
const result = build(source);
assert.deepEqual(result.entries.map(e => e.senses.length), [11, 46, 6]);
const [di, fare, tempo] = result.entries;
assert(di.senses.every(s => s.pos === 'preposition'));
assert(di.excludedSections.some(s => s.heading === 'Number'));
assert(di.excludedSections.some(s => s.heading === 'Usage Note'));
assert(di.aliases.some(a => a.headword === 'dovere'));
assert(fare.aliases.some(a => a.headword === 'farsi'));
assert.equal(fare.senses.find(s => s.definition.text === '(transitive) to make').details.length, 9);
assert(tempo.senses.find(s => s.definition.text === 'weather').details.some(d => d.text.includes('Synonym: clima')));
assert(!tempo.senses.some(s => s.definition.text.startsWith('Synonym:')));
for (const entry of result.entries) for (const sense of entry.senses) {
  assert.equal(sense.definition.language, 'en');
  assert.equal(sense.review.status, 'unreviewed');
  assert.equal(sense.preferred, false);
  assert.equal(sense.register, 'unknown');
  assert.equal(sense.confidence, 'unassessed');
  assert.equal(sense.source.archiveSha256, source.sha256);
  assert.equal(sense.license.identifier, 'CC-BY-SA-4.0');
}
const synthetic = parseMatch({method:'direct',headword:'test',html:'<script>bad()</script><p><b>Noun</b></p><ol><li>one<ol><li>child</li></ol></li><ol><li>sibling child</li></ol></ol><p><b>Noun</b></p><ol><li>two &lt;img&gt;</li></ol><p><b>Usage Note</b></p><ol><li>note</li></ol>'});
assert.equal(synthetic.sections[0].items[0].text, 'one');
assert.deepEqual(synthetic.sections[0].items[0].details.map(d=>d.text), ['child','sibling child']);
assert.notEqual(synthetic.sections[0].position, synthetic.sections[1].position);
assert.equal(synthetic.sections[1].items[0].text, 'two <img>');
assert(!JSON.stringify(synthetic).includes('bad()'));
assert.throws(()=>build({...source,entries:source.entries.slice(1)}), /Three-word/);
assert.equal(fs.readFileSync(path.join(base, 'reader-dict-en-trial.json'), 'utf8'), JSON.stringify(result,null,2)+'\n');
console.log('English reader.dict trial checks passed.');
const lens = require('../prototype-0.5-media-shell/word-lens-trial');
assert.equal(lens.lookup(result, 'DI').headword, 'di');
assert.equal(lens.lookup(result, 'dì'), null);
assert.equal(lens.lookup(result, 'farsi'), null);
assert.equal(lens.render(undefined, 'di'), '');
