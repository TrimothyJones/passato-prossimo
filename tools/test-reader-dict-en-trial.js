assert(!lens.render(hostile, 'di').includes('<img'));
const bundle = {window:{}};
require('node:vm').runInNewContext(fs.readFileSync(path.join(base, '../reader-dict-en-trial.js'), 'utf8'), bundle);
assert.equal(JSON.stringify(bundle.window.READER_DICT_EN_TRIAL), JSON.stringify(result));
