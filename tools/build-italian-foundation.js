const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { exactKey } = require("../prototype-0.5-media-shell/lexical-provider");

const root = path.resolve(__dirname, "..");
const authorPath = path.join(root, "prototype-0.5-media-shell/data/italian-foundation.json");
const outputPath = path.join(root, "prototype-0.5-media-shell/italian-foundation.js");
const nonempty = (value) => typeof value === "string" && value.trim().length > 0;
const nullableText = (value) => value === null || nonempty(value);

function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.keys(value).sort().map((key) => [key, canonical(value[key])]));
  }
  return value;
}

function contentHash(entry) {
  const { review, ...content } = entry;
  return crypto.createHash("sha256").update(JSON.stringify(canonical(content))).digest("hex");
}

function validate(data) {
  const requireValue = (condition, message) => { if (!condition) throw new Error(message); };
  requireValue(data?.schemaVersion === 1 && data.providerId === "italian-foundation"
    && nonempty(data.revision) && Array.isArray(data.entries), "Invalid foundation envelope");
  const ids = new Set();
  const defaults = new Set();
  for (const entry of data.entries) {
    const check = (condition, message) => requireValue(condition, `${entry?.id || "record"}: ${message}`);
    check(entry && nonempty(entry.id) && !ids.has(entry.id), "unique ID required");
    ids.add(entry.id);
    check(nonempty(entry.headword) && entry.headword === exactKey(entry.headword), "canonical exact headword required");
    check(entry.language === "it" && ["article", "preposition", "conjunction", "pronoun", "verb", "adjective", "noun"].includes(entry.pos), "invalid language/POS");
    check(nonempty(entry.definition?.text) && entry.definition.language === "en", "English definition required");
    check(typeof entry.preferred === "boolean" && nullableText(entry.usageNote), "preference and usage note required");
    const source = entry.source;
    check(["original", "adapted"].includes(source?.kind) && nonempty(source.author)
      && nonempty(source.attribution) && Array.isArray(source.references) && source.references.length > 0, "source metadata required");
    for (const reference of source.references) {
      check(nonempty(reference.locator) && nonempty(reference.senseLocator)
        && ["evidence", "adapted-from"].includes(reference.relation), "invalid source reference");
    }
    check(source.kind !== "adapted" || source.references.some((ref) => ref.relation === "adapted-from"), "adaptation needs source reference");
    check(["pending", "verified", "blocked"].includes(entry.license?.status)
      && nullableText(entry.license.expression) && nullableText(entry.license.evidence), "license metadata required");
    check(["unassessed", "medium", "high"].includes(entry.confidence), "invalid confidence");
    check(["neutral", "informal", "formal", "literary", "archaic", "unknown"].includes(entry.register), "invalid register");
    const review = entry.review;
    check(["draft", "in-review", "approved", "rejected"].includes(review?.status)
      && nullableText(review.reviewer) && nullableText(review.reviewedAt)
      && nullableText(review.contentHash) && nonempty(review.note), "review metadata required");
    if (review.status === "approved") {
      check(entry.license.status === "verified" && nonempty(entry.license.expression)
        && nonempty(entry.license.evidence), "approval needs verified reuse evidence");
      check(entry.confidence === "high" && entry.register !== "unknown", "approval needs assessed confidence/register");
      check(nonempty(review.reviewer) && /^\d{4}-\d{2}-\d{2}T/.test(review.reviewedAt || "")
        && Number.isFinite(Date.parse(review.reviewedAt)), "approval needs reviewer and ISO timestamp");
      check(review.contentHash === contentHash(entry), "content changed or review hash missing; renew review");
      const group = `${entry.headword}:en`;
      if (entry.preferred) {
        check(!defaults.has(group), "conflicting approved defaults");
        defaults.add(group);
      }
    }
  }
  return data;
}

function compile(data) {
  validate(data);
  const approved = data.entries.filter((entry) => entry.review.status === "approved");
  const defaults = new Set(approved.filter((entry) => entry.preferred).map((entry) => entry.headword));
  const entries = approved.filter((entry) => defaults.has(entry.headword))
    .sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
  return { schemaVersion: 1, providerId: data.providerId, revision: data.revision, entries };
}

function render(data) {
  return `// Generated by npm run build:foundation. Do not edit.\nwindow.ITALIAN_FOUNDATION = ${JSON.stringify(compile(data), null, 2)};\n`;
}

if (require.main === module) {
  const data = JSON.parse(fs.readFileSync(authorPath, "utf8"));
  const output = compile(data);
  if (!process.argv.includes("--check")) fs.writeFileSync(outputPath, render(data));
  console.log(`Foundation: ${data.entries.length} authored; ${output.entries.length} publishable.`);
  for (const entry of data.entries) {
    if (!output.entries.some((published) => published.id === entry.id)) {
      console.log(`Excluded ${entry.id}: ${entry.review.status === "approved" ? "no approved default in group" : entry.review.status}`);
    }
  }
}

module.exports = { validate, compile, render, contentHash };
