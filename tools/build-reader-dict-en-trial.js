const fs = require('node:fs');
const path = require('node:path');
const cheerio = require('cheerio');
const root = path.resolve(__dirname, '..', 'prototype-0.5-media-shell/data');
const clean = text => text.replace(/\s+/g, ' ').trim();
const allowed = { di: ['Preposition'], fare: ['Verb', 'Noun'], tempo: ['Noun'] };

// Nested lists may be children of a li OR siblings immediately after it.
// Keep their parent relationship without claiming every item is a definition.
function readList($, list) {
  const items = [];
  $(list).children().each((_, node) => {
    if (node.name === 'li') {
      const copy = $(node).clone();
      copy.find('ol,ul').remove();
      const item = { text: clean(copy.text()), details: [] };
      $(node).children('ol,ul').each((_, child) => item.details.push(...readList($, child)));
      items.push(item);
    } else if (node.name === 'ol' || node.name === 'ul') {
      if (!items.length) throw new Error('Nested list without a parent item');
      items[items.length - 1].details.push(...readList($, node));
    } else throw new Error(`Unexpected list element: ${node.name}`);
  });
  return items;
}

function parseMatch(match) {
  const $ = cheerio.load(match.html);
  $('script,style,iframe,object').remove();
  const sections = [], supplemental = [];
  let section;
  $('body').contents().each((_, node) => {
    const text = clean($(node).text());
    if (!text) return;
    const heading = node.name === 'p' ? clean($(node).children('b').first().text()) : '';
    if (heading) {
      section = { position: sections.length + 1, heading, headingText: text, items: [] };
      sections.push(section);
    } else if (node.name === 'ol' || node.name === 'ul') {
      if (!section) throw new Error('List without a section');
      section.items.push(...readList($, node));
    } else {
      supplemental.push(text);
      section = null;
    }
  });
  return { method: match.method, headword: match.headword, sections, supplemental };
}

function build(source) {
  if (source.entries.map(e => e.word).join(',') !== 'di,fare,tempo') throw new Error('Three-word trial only');
  const { entries, ...metadata } = source;
  return { schemaVersion: 1, providerId: 'reader-dict-it-en-trial', source: metadata,
    changes: 'Three-word subset; plain text; selected grammatical sections; nested source details retain parent context; aliases and excluded sections preserved separately. No sense alignment or learner approval.',
    entries: entries.map(entry => {
      const matches = entry.matches.map(parseMatch);
      const direct = matches.filter(m => m.method === 'direct' && m.headword === entry.word);
      if (direct.length !== 1) throw new Error(`Expected one exact entry: ${entry.word}`);
      const selected = direct[0].sections.filter(s => allowed[entry.word].includes(s.heading));
      return { headword: entry.word,
        senses: selected.flatMap(section => section.items.map((item, index) => ({
          id: `${source.sha256}:${entry.word}:${section.position}:${index + 1}`,
          headword: entry.word, language: 'it', pos: section.heading.toLowerCase(),
          sourceSection: section.heading, definition: { text: item.text, language: 'en' },
          details: item.details, preferred: false, register: 'unknown', confidence: 'unassessed',
          review: { status: 'unreviewed' }, license: source.license,
          source: { providerId: 'reader-dict-it-en-trial', archiveSha256: source.sha256,
            url: source.url, attribution: source.attribution,
            locator: `${entry.word} / section ${section.position} / item ${index + 1}` }
        }))),
        excludedSections: direct[0].sections.filter(s => !selected.includes(s)).map(s => ({ ...s,
          reason: 'Outside the grammatical sections selected for this three-word trial' })),
        supplemental: direct[0].supplemental,
        aliases: matches.filter(m => m.method === 'alias')
      };
    }) };
}
if (require.main === module) {
  const source = JSON.parse(fs.readFileSync(path.join(root, 'research/reader-dict-it-en-sample.json'), 'utf8'));
  const result = build(source);
  fs.writeFileSync(path.join(root, 'reader-dict-en-trial.json'), JSON.stringify(result, null, 2) + '\n');
  fs.writeFileSync(path.join(root, '../reader-dict-en-trial.js'), '// Generated by tools/build-reader-dict-en-trial.js. Dictionary data: CC BY-SA 4.0.\nwindow.READER_DICT_EN_TRIAL = ' + JSON.stringify(result).replace(/</g, '\\u003c') + ';\n');
  console.log(result.entries.map(e => `${e.headword}: ${e.senses.length} top-level English definitions`).join('; '));
}
module.exports = { build, parseMatch };
